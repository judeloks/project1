from turtle import *

def house():
    color("black", "grey")
    pensize(2)
    penup()
    goto(-150,0)
    pendown()
    begin_fill()
    for i in range(2):
        forward(100)
        left(90)
        forward(200)
        left(90)
    end_fill()

